// Generates components/icons.generated.ts: inline SVG paths for exactly the Material Symbols
// (Rounded, weight 400) the app uses — a few KB instead of a multi-MB icon font, and no flash.
// Run: node scripts/build-icons.mjs  (re-run after using a new icon name)

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'node_modules/@material-symbols/svg-400/rounded';
const files = [...readdirSync('components'), ...readdirSync('lib')].filter(f => /\.tsx?$/.test(f) && !f.includes('generated'));
const text = files.map(f => readFileSync(existsSync(join('components', f)) ? join('components', f) : join('lib', f), 'utf8')).join('\n');
// Only lines that mention an icon: <Icon name=…>, TYPE_ICON, icon: '…', LIVE_ICON, etc.
const iconLines = text.split('\n').filter(l => /icon|Icon|ICON/.test(l)).join('\n');
// Icons reached only through multi-line maps (TYPE_ICON) are listed explicitly.
const EXTRA = ['flight', 'train', 'directions_boat', 'directions_bus', 'directions_car', 'hotel', 'local_activity', 'restaurant'];
const candidates = new Set([...EXTRA, ...[...iconLines.matchAll(/['"`]([a-z][a-z0-9_]{1,40})['"`]/g)].map(m => m[1])]);
const pathOf = file => readFileSync(join(SRC, file), 'utf8').match(/ d="([^"]+)"/)?.[1];

const out = {};
for (const name of [...candidates].sort()) {
  if (!existsSync(join(SRC, `${name}.svg`))) continue;
  const o = pathOf(`${name}.svg`);
  const f = existsSync(join(SRC, `${name}-fill.svg`)) ? pathOf(`${name}-fill.svg`) : o;
  out[name] = f === o ? [o] : [o, f];
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
writeFileSync('components/icons.generated.ts',
  `// GENERATED by scripts/build-icons.mjs — do not edit. Material Symbols Rounded (Apache-2.0).\n` +
  `export const ICONS: Record<string, [string] | [string, string]> = {\n${body}\n};\n`);
console.log(`${Object.keys(out).length} icons`, Object.keys(out).join(' '));
